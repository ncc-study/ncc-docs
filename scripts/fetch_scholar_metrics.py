"""Fetch Google Scholar bibliometrics for the NCC study profile.

Writes _scholar-metrics.md (included on the landing page) with total
citations, h-index and i10-index. Run by the publish workflow before
rendering; can also be run locally to refresh the committed fallback.

Google Scholar has no API and often blocks requests from CI runners, so a
failed fetch is not an error: the script leaves the existing file untouched
and exits 0, and the site builds with the last committed values.

Usage: python scripts/fetch_scholar_metrics.py SCHOLAR_USER_ID
"""

import datetime
import pathlib
import sys

OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "_scholar-metrics.md"


def fetch_metrics(user_id):
    from scholarly import scholarly

    author = scholarly.search_author_id(user_id)
    author = scholarly.fill(author, sections=["indices"])
    metrics = {
        "citations": author.get("citedby"),
        "h_index": author.get("hindex"),
        "i10_index": author.get("i10index"),
    }
    missing = [key for key, value in metrics.items() if not isinstance(value, int)]
    if missing:
        raise ValueError(f"profile response is missing {', '.join(missing)}")
    return metrics


def render_markdown(metrics, user_id, retrieved):
    url = f"https://scholar.google.com/citations?user={user_id}"
    tiles = [
        ("Citations", metrics["citations"]),
        ("h-index", metrics["h_index"]),
        ("i10-index", metrics["i10_index"]),
    ]
    lines = [
        "<!-- Generated by scripts/fetch_scholar_metrics.py — do not edit by hand. -->",
        "",
        ":::: {.scholar-metrics}",
    ]
    for label, value in tiles:
        lines += [
            "::: {.scholar-metric}",
            f"[{value:,}]{{.scholar-value}}",
            f"[{label}]{{.scholar-label}}",
            ":::",
        ]
    lines += [
        "::::",
        "",
        f"[Source: [Google Scholar]({url}), retrieved {retrieved.isoformat()}.]{{.scholar-source}}",
        "",
    ]
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__.strip().splitlines()[-1])
    user_id = sys.argv[1]

    try:
        metrics = fetch_metrics(user_id)
    except Exception as error:  # any failure falls back to the committed file
        print(f"::warning::Google Scholar fetch failed, keeping existing metrics: {error}")
        return

    retrieved = datetime.datetime.now(datetime.timezone.utc).date()
    OUTPUT.write_text(render_markdown(metrics, user_id, retrieved), encoding="utf-8")
    print(f"Wrote {OUTPUT.name}: {metrics}")


if __name__ == "__main__":
    main()
